//! Integration tests: the bitwise and shift operators (`& | ^ << >> >>>`),
//! unary `~`, and their compound assignments apply `ToNumeric` then
//! `ToInt32`/`ToUint32` per spec, including operands beyond the `i64` range.

mod common;
use common::{assert_number, assert_output, assert_string, assert_uncaught};

#[test]
fn basic_results() {
    assert_number("5 & 3", 1.0);
    assert_number("5 | 3", 7.0);
    assert_number("5 ^ 3", 6.0);
    assert_number("~5", -6.0);
    assert_number("-1 >>> 0", 4_294_967_295.0);
    assert_number("let x = 5; ~x", -6.0);
}

#[test]
fn results_are_never_negative_zero() {
    assert_number("1 / (-0 | 0)", f64::INFINITY);
    assert_number("1 / (0 >>> 0)", f64::INFINITY);
    assert_number("1 / (-0 >> 0)", f64::INFINITY);
    assert_number("1 / ~~-0", f64::INFINITY);
    assert_number("let z = -0; 1 / (z & -1)", f64::INFINITY);
}

#[test]
fn shift_counts_are_masked() {
    assert_number("1 << -1", -2_147_483_648.0);
    assert_number("1 << 32", 1.0);
    assert_number("1 << 33", 2.0);
    assert_number("1 << 31", -2_147_483_648.0);
    assert_number("-8 >> 1", -4.0);
    assert_number("-8 >>> 1", 2_147_483_644.0);
    assert_number("-1 >>> 0", 4_294_967_295.0);
    assert_number("(2**32+1) >>> 0", 1.0);
    assert_number("-1 >>> 31", 1.0);
    assert_number("-1 >>> 32", 4_294_967_295.0);
    assert_number("-1 >> 33", -1.0);
    assert_number("16 >> 4294967300", 1.0);
}

#[test]
fn primitive_operands_coerce() {
    assert_number(r#""12" & "10""#, 8.0);
    assert_number(r#""0x10" | 0"#, 16.0);
    assert_number(r#""abc" | 0"#, 0.0);
    assert_number(r#"~"7""#, -8.0);
    assert_number(r#""-1" >>> "0""#, 4_294_967_295.0);
    assert_number("true | 2", 3.0);
    assert_number("false ^ 1", 1.0);
    assert_number("null | 5", 5.0);
    assert_number("undefined | 5", 5.0);
    assert_number("~null", -1.0);
    assert_number("~undefined", -1.0);
    assert_number("[3] << [2]", 12.0);
}

#[test]
fn object_operands_use_value_of() {
    assert_number("const o = { valueOf() { return 6; } }; o & 3", 2.0);
    assert_number(
        "const o = { valueOf() { return -1; } }; o >>> 0",
        4_294_967_295.0,
    );
    assert_number("const o = { toString() { return '9'; } }; ~o", -10.0);
}

#[test]
fn operands_are_coerced_left_to_right() {
    assert_output(
        "const a = { valueOf() { console.log('a'); return 1; } };\n\
         const b = { valueOf() { console.log('b'); return 2; } };\n\
         const r = [a | b, a << b, a >>> b]; console.log(r.join());",
        "a\nb\na\nb\na\nb\n3,4,0\n",
    );
}

#[test]
fn throwing_value_of_propagates() {
    let o = "const o = { valueOf() { throw new RangeError('boom'); } };";
    assert_uncaught(&format!("{o} o | 0"), "RangeError: boom");
    assert_uncaught(&format!("{o} 1 >>> o"), "RangeError: boom");
    assert_uncaught(&format!("{o} ~o"), "RangeError: boom");
    assert_output(
        &format!(
            "{o} const b = {{ valueOf() {{ console.log('rhs'); return 1; }} }};\n\
             try {{ o & b; }} catch (e) {{ console.log(e.message); }}"
        ),
        "boom\n",
    );
}

#[test]
fn compound_assignment_on_local() {
    assert_string(
        "let a = 12; a &= 10; let b = 12; b |= 3; let c = 5; c ^= 1;\n\
         let d = 1; d <<= 4; let e = -16; e >>= 2; let f = -1; f >>>= 28;\n\
         [a, b, c, d, e, f].join()",
        "8,15,4,16,-4,15",
    );
    assert_number("let x = 6; x |= 1", 7.0);
}

#[test]
fn compound_assignment_on_member() {
    assert_string(
        "const o = { k: 12 }; o.k &= 10; const p = { k: -1 }; p.k >>>= 0;\n\
         [o.k, p.k].join()",
        "8,4294967295",
    );
}

#[test]
fn compound_assignment_on_computed_member_evaluates_key_once() {
    assert_output(
        "let n = 0; function f() { n++; return 'k'; }\n\
         const o = { k: 4 }; o[f()] |= 1; o[f()] <<= 2;\n\
         const a = [1, 2]; let i = 0; a[i++] ^= 3;\n\
         console.log(o.k, n, a.join(), i);",
        "20 2 2,2 1\n",
    );
}

#[test]
fn compound_assignment_on_captured_variable() {
    assert_number(
        "let flags = 0; function set(b) { flags |= 1 << b; } set(0); set(3); set(31); flags >>> 0",
        2_147_483_657.0,
    );
}

#[test]
fn decimal_to_hex_string_pattern() {
    assert_string(
        "function f(n) { n = n >>> 0; var h = '';\n\
         for (var i = 7; i >= 0; i--) { h += '0123456789ABCDEF'.charAt((n >> (i * 4)) & 0xF); }\n\
         return h; }\n\
         [f(255), f(-1), f(0), f(4294967296 + 16)].join()",
        "000000FF,FFFFFFFF,00000000,00000010",
    );
}

